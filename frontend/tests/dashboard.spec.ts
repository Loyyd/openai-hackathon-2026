test('polling pauses when hidden, resumes on return, prevents overlap and times out', async ({ page }) => {
  const state = await installApi(page);
  await page.clock.install();
  await openDashboard(page);
  const initialReads = state.mapReads;
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')); });
  await page.clock.fastForward(30_000);
  expect(state.mapReads).toBe(initialReads);
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: false }); document.dispatchEvent(new Event('visibilitychange')); });
  await expect.poll(() => state.mapReads).toBe(initialReads + 1);
  await expect(page.getByRole('button', { name: 'Refresh data' })).toBeEnabled();
  let release!: (value: MapData) => void;
  state.nextMap = new Promise((resolve) => { release = resolve; });
  await page.getByRole('button', { name: 'Refresh data' }).click();
  await expect.poll(() => state.mapReads).toBe(initialReads + 2);
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  expect(state.mapReads).toBe(initialReads + 2);
  await page.clock.fastForward(10_100);
  await page.getByRole('button', { name: 'Diagnostics' }).click();
  await expect(page.getByText('The request timed out. Please retry.', { exact: true })).toBeVisible();
  await expect(page.getByTestId('active-count')).toHaveText('5');
  release({ cameras: [], incidents: [], transport: [] });
  await expect(page.getByTestId('active-count')).toHaveText('5');
});
