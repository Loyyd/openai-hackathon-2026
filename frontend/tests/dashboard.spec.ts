test('an in-flight workflow read and a later stale read cannot undo a completed save', async ({ page }) => {
  const state = await installApi(page, { user: operator });
  await page.clock.install();
  await openDashboard(page);
  let release!: (value: IncidentWorkflow[]) => void;
  state.nextWorkflows = new Promise((resolve) => { release = resolve; });
  const reads = state.workflowReads;
  await page.getByRole('button', { name: 'Refresh data' }).click();
  await expect.poll(() => state.workflowReads).toBeGreaterThan(reads);
  const dialog = await openIncident(page);
  await dialog.getByRole('button', { name: 'Resolve incident' }).click();
  await expect(dialog.getByRole('button', { name: 'Resolved', exact: true })).toBeVisible();
  release([]);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Refresh data' })).toBeEnabled();
  await expect(page.getByTestId('active-count')).toHaveText('4');
  state.workflows = [];
  await page.clock.fastForward(15_000);
  await expect.poll(() => state.workflowReads).toBeGreaterThan(reads + 1);
  await expect(page.getByTestId('active-count')).toHaveText('4');
});

